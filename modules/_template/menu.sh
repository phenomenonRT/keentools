#!/bin/sh
# menu.sh — необязательный скрипт. Если он есть, при выборе этого модуля
# в главном меню KeenTools управление полностью передаётся сюда (вместо
# стандартного меню "Запустить/Остановить/.../Удалить"). Внутри доступны
# те же переменные окружения: KT_HOME, KT_MODULE_DIR.
#
# Здесь можно рисовать что угодно — например, собственные подпункты,
# статистику проекта, сложную настройку и т.д. Стандартные функции
# менеджера (kt_*) недоступны напрямую (это отдельный процесс), но
# можно вызывать стандартные скрипты жизненного цикла модуля напрямую:
#   "$KT_MODULE_DIR/start.sh"
#   "$KT_MODULE_DIR/stop.sh"
#
# Если этот файл отсутствует — KeenTools покажет стандартное меню и
# автоматически скроет пункты для тех скриптов, которых нет у модуля
# (например, если нет restart.sh — пункта "Перезапустить" не будет).

while true; do
    clear 2>/dev/null
    echo "================================"
    echo " Своё меню проекта (пример)"
    echo "================================"
    echo "1. Запустить"
    echo "2. Остановить"
    echo "0. Назад"
    printf "Выбор: "
    kt_read c
    case "$c" in
        1) "$KT_MODULE_DIR/start.sh"; printf "\nEnter..."; kt_read _ ;;
        2) "$KT_MODULE_DIR/stop.sh"; printf "\nEnter..."; kt_read _ ;;
        0) exit 0 ;;
        *) echo "Неверный выбор" ;;
    esac
done
