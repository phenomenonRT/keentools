#!/bin/sh
# configure.sh — показывает путь и содержимое settings.json awg-manager.
# Основная настройка (туннели, порт, авторизация) делается через
# веб-интерфейс сервиса; этот пункт — только для просмотра/диагностики.
cfg="/opt/etc/awg-manager/settings.json"

if [ ! -f "$cfg" ]; then
    echo "Файл настроек не найден: $cfg"
    exit 1
fi

echo "Файл настроек: $cfg"
echo "----------------------------------------"
cat "$cfg"
echo "----------------------------------------"
echo
echo "Веб-интерфейс доступен по адресу http://<IP роутера>:<port>"
echo "(порт указан в поле \"port\" выше, по умолчанию 2222)"
